package Level1.Multiplicacion;

/**
 * Clase que obtiene el cuadrado y cubo de un numero
 * 
 * @author Moisés
 * @version 1.0
 */
public class Ejercicio36 {

    /**
     * Metodo main que imprime el resultado del cuadrado y cubo 
     * @param val valor int 
     */
    public static void main(String[] args) {

        int val = 7;

        System.out.println("El cuadrado de 7 es:" + (val * val));
        System.out.println("El cubo de 7 es:" + (val * val * val));

    }
}
