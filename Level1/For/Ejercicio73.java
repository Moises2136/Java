package Level1.For;

/**
 * Clase Números pares del 1 al 50
 * 
 * @author Moisés
 * @version 1.0
 */
public class Ejercicio73 {
    public static void main(String[] args) {

        for (int i = 1; i <= 50; i++) {
            i += 1;
            System.out.println("Numero par: " + i);
        }

        for (int i = 0; i <= 50; i++) {
            i += 1;
            System.out.println("Numero impar: " + i);
        }

    }
}
