package Level1.While_do_while;

/**
 * Clase Contador del 1 al 10 con while
 * 
 * @author Moisés
 * @version 1.0
 */
public class Ejercicio81 {
    public static void main(String[] args) {

        int contador = 1;

        while (contador <= 10) {
            System.out.println("Numero:" + contador);
            contador++;
        }

    }
}
